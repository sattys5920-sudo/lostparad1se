// 앱을 켜 두었는가 — **꺼진 사람은 맵에서 사라진다.**
//
// 앱이 화면에 떠 있는 동안 1 분마다 서버에 「켜 있다」를 적는다(ping). 마지막
// 신호가 5 분 넘게 끊기면 꺼진 사람이다. 꺼진 사람은 남의 맵에 안 그려지고
// 칸도 막지 않는다 — 앱을 끈 채 길 한가운데 서 있는 사람이 길을 막았다.
// **방 정원에는 센다.** 방 안에 있는 것은 그대로다. 다시 켜면 바로 돌아온다.
//
// 시각은 **실제 시각**이다. 게임 시계는 운영자가 빨리 돌릴 수 있어서
// 「5 분 동안 안 켰다」를 잴 수 없다.

/** 이만큼 신호가 없으면 꺼진 것으로 본다 */
export const AWAY_MS = 5 * 60_000
/** 켜 있는 동안 신호를 보내는 간격 */
export const PING_MS = 60_000

/**
 * 꺼진 사람인가. **신호를 한 번도 안 보낸 사람은 아니다** — 이 규칙이 생기기
 * 전 화면을 아직 쓰는 사람까지 한꺼번에 사라지면 안 된다.
 */
export const isAway = (seenMs: number | null | undefined, realNowMs: number): boolean =>
  typeof seenMs === 'number' && realNowMs - seenMs > AWAY_MS
