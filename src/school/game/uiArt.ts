/**
 * 점령전 행동은 하나도 그림 없이 나가면 안 된다.
 *
 * 열쇠가 곧 ActionKind 라, 행동 종류가 늘면 여기서 **컴파일이
 * 멈춘다** — 이름표에 줄 하나 빠뜨린 채 빈 칸으로 나가는 일이 없다.
 * 이동만 빠진다. 그것은 맵에서 걸어서 하는 것이라 이 목록에 없다.
 */
const ACT_ART: Record<Exclude<ActionKind, 'move'>, true> = {
  research: true,
  summon: true,
  disturb: true,
  disguise: true,
  dropRobot: true,
  smashRobot: true,
}

/** 8칸짜리 셋. 나머지는 16칸이다. */
const SMALL = new Set(['token', 'money', 'knowledge'])

// 그림이 틀어진 채로 나가지 않게 여기서 막는다. 줄 수나 칸 수가 맞지
// 않거나 모르는 색이 섞이면 화면이 뜨기 전에 터진다
for (const key of Object.keys(ACT_ART)) {
  if (!UI_ART[key]) throw new Error(`${key}: 행동 그림이 없다`)
}

for (const [key, rows] of Object.entries(UI_ART)) {
  const n = SMALL.has(key) ? 8 : 16
  if (rows.length !== n) throw new Error(`${key}: ${rows.length}줄이다. ${n}줄이어야 한다`)
  for (const [i, r] of rows.entries()) {
    if (r.length !== n) throw new Error(`${key} ${i}번째 줄이 ${r.length}칸이다`)
    for (const c of r) if (!' 012345'.includes(c)) throw new Error(`${key}: 모르는 색 ${c}`)
  }
}

const CH: Record<string, string | null> = {
  ' ': null,
  '0': PAL.paper,
  '1': PAL.light,
  '2': PAL.mid,
  '3': PAL.ink,
  '4': UI.gold,
  '5': UI.ice,
}

const baked = new Map<string, string>()

/**
 * 그 그림을 한 번 구워 두고 다시 쓴다.
 *
 * 조작부는 자원이 바뀔 때마다 다시 그려진다. 그때마다 캔버스를 새로
 * 만들면 열두 개가 한꺼번에 구워진다.
 */
export function uiIcon(key: string): string {
  const has = baked.get(key)
  if (has) return has
  const rows = UI_ART[key]
  if (!rows) return ''
  const n = SMALL.has(key) ? 8 : 16
  const canvas = document.createElement('canvas')
  canvas.width = n
  canvas.height = n
  const ctx = canvas.getContext('2d')
  if (!ctx) return ''
  for (const [y, row] of rows.entries()) {
    for (const [x, c] of [...row].entries()) {
      const color = CH[c]
      if (!color) continue
      ctx.fillStyle = color
      ctx.fillRect(x, y, 1, 1)
    }
  }
  const url = canvas.toDataURL()
  baked.set(key, url)
  return url
}
