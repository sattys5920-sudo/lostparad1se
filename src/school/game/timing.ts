/** 채팅을 다시 가져오는 간격. */
export const CHAT_POLL_MS = 2500

/** 한 칸(16px)을 걷는 데 걸리는 시간. 방 안 걸음이다. */
export const STEP_MS = 160
/**
 * 걷기 자세가 1초에 몇 번 바뀌는지. 프레임 수가 아니라 시간으로 센다 —
 * 화면 주사율이 달라도 걸음걸이가 같아야 한다.
 */
export const WALK_POSES_PER_SEC = 3.2

/** 미니맵을 켜 뒀는지. 이 기기에만 남는다. */
export const MINIMAP_ON_KEY = 'lostparad1se.minimap'

/**
 * 걸어 다니는 학교를 몇 배로 그리는가. 도트를 키워야 휴대폰에서 보인다.
 *
 * 이 값이 방 크기를 정한다 — 배율이 높을수록 화면에 들어오는 칸이 줄고,
 * 방과 양옆 벽이 한 화면에 안 들어오면 제 방의 문이 안 보인다.
 */
/**
 * 게임 화면이 그리는 논리 화소. **정사각이다.**
 *
 * 실제 화면 크기가 얼마든 이 크기로 그리고, 정수 배로 늘려서 붙인다.
 * 375 폭이면 2배(320), 더 넓으면 3배까지. 소수 배율을 쓰면 한 픽셀이
 * 1.4픽셀이 되어 줄 굵기가 들쭉날쭉해지고, 도트 그림에서는 그게 바로
 * 뭉개져 보인다.
 */
export const MIN_VIEW_PX = 160

/** 이보다 크게는 안 늘린다. 너무 크면 방이 한 칸만 보인다. */
export const MAX_SCALE = 3

/** @deprecated 정수 배율로 바뀌었다. 남은 자리에서만 쓴다. */
export const CANVAS_SCALE = 2

/**
 * 문을 넘자고 말한 뒤 대답을 기다리는 한도(밀리초).
 *
 * 이 시간이 지나면 화면이 스스로 푼다. 대답이 아예 안 오는 경우 —
 * 끊긴 연결, 잃어버린 응답 — 에 이게 없으면 그 판 내내 어느 문도
 * 못 넘는다. 실제로 한 번 그렇게 막혔다.
 */
export const CROSS_TIMEOUT_MS = 4000

/** 가장 좁은 화면. 여기서 되면 어디서나 된다. */
export const NARROW_PX = 380

/**
 * 십자키를 이만큼 누르고 있으면 이어 걷기 시작한다.
 *
 * 0이면 톡 누른 것도 두 칸이 되고, 너무 길면 「꾹 눌러도 안 간다」가
 * 된다. 손가락이 단추에 닿았다 떨어지는 데 보통 100ms 안쪽이라,
 * 그보다 넉넉히 잡는다.
 */
export const PAD_HOLD_MS = 280

/**
 * 지도 위에 사람을 몇 화소로 그릴까.
 *
 * 스프라이트 원본은 32×32이고 바닥 한 칸은 16화소다 — 그대로 그리면
 * **두 칸 키**라 방보다 사람이 먼저 보인다. 한 칸 반으로 줄인다.
 *
 * 32의 0.75배라 나누어떨어지지 않는다. 네 줄에 한 줄이 빠지므로
 * 도트가 아주 깨끗하지는 않다 — 얼굴이 보이는 크기와 깨끗함 중에
 * 얼굴 쪽을 골랐다. 완전히 깨끗하게 가려면 16(정확히 절반)이고,
 * 24 비율 그대로 깨끗하려면 스프라이트를 24×24로 다시 그려야 한다.
 */
export const CHAR_PX = 24
