// 방마다 다른 소품 그림.
//
// **팔레트는 넷뿐이다**(sprites.ts 의 PAL). 0 은 밝은 면, 1 은 회색,
// 2 는 중간 톤, 3 은 윤곽과 그늘이다. 빈칸은 투명이라 바닥이 비친다.
// 새 색을 만들지 않는다 — 스물다섯 방이 같은 눈밭 톤 안에 있어야 한다.
//
// 한 칸은 16×16 이다. 가로로 두 칸이면 32 글자, 세로로 두 칸이면 32 줄.
// 크기는 그림에서 저절로 나오므로 따로 적지 않는다(sprites.ts 의 PROP_TILES).
//
// 벽에 붙는 것(액자·칠판·거울)은 아래쪽 절반을 비워 둔다. 벽 칸 위에
// 얹히므로 아랫단이 차 있으면 벽이 두꺼워 보인다.

/** 16×16 한 칸. 짧게 적은 줄은 오른쪽을 공백으로 채운다. */
const T = (rows: string[]): string[] => rows.map((r) => r.padEnd(16, ' ').slice(0, 16))
/** 32×16 — 가로 두 칸. */
const T2 = (rows: string[]): string[] => rows.map((r) => r.padEnd(32, ' ').slice(0, 32))

