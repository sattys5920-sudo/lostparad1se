// 그림이 빠진 채로 나가지 않게 여기서 막는다. 물건마다 하나씩이라,
// 심부름을 더하면 그림도 같이 더해야 한다
for (const [key, rows] of Object.entries(THING_ART)) {
  if (rows.length !== 12) throw new Error(`${key}: ${rows.length}줄이다. 12줄이어야 한다`)
  for (const [i, r] of rows.entries()) {
    if (r.length !== 12) throw new Error(`${key} ${i}번째 줄이 ${r.length}칸이다`)
    for (const c of r) if (!' 0123'.includes(c)) throw new Error(`${key}: 모르는 색 ${c}`)
  }
}

