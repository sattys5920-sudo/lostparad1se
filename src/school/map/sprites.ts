// 팀 무늬는 바닥을 가리지 않고 그 위에 얹는다 — 어느 실인지와 누구 땅인지를 함께 보여야 한다.
function teamPattern(mark: (x: number, y: number) => boolean): string[] {
  return grid((x, y) => (mark(x, y) ? '2' : ' '))
}

