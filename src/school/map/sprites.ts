// 흑백이라 색으로 팀을 구분할 수 없다. 바닥 무늬로 나눈다 —
// 어느 구역에 들어선 순간 발밑을 보면 누구 땅인지 안다.

function grid(mark: (x: number, y: number) => string): string[] {
  const rows: string[] = []
  for (let y = 0; y < 16; y++) {
    let row = ''
    for (let x = 0; x < 16; x++) row += mark(x, y)
    rows.push(row)
  }
  return rows
}

/** 흙바닥 — 정원·운동장·옥상. 자잘한 알갱이만 흩어 둔다. */
